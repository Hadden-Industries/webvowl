import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { format } from "prettier";

// Compile the provider's untouched schemas at authoring time. Browsers need no eval or schema fetch.
const directory = new URL(
  "../src/ontology-loading/contracts/",
  import.meta.url,
);
const ajv = new Ajv2020({
  strict: true,
  validateFormats: false,
  code: { source: true, esm: true, lines: true },
});
// Ajv resolves standard anchors but omits their keyword declaration in strict mode.
ajv.addKeyword({ keyword: "$anchor", schemaType: "string" });
const names = {
  resolution: "ontology-resolution",
  pointer: "ontology-source-pointer",
  version: "ontology-source-version",
  validation: "ontology-validation",
  policy: "ontology-loader-policy",
  materialization: "ontology-materialization-status",
  refresh: "ontology-refresh-result",
  error: "ontology-materialization-error",
};
for (const name of readdirSync(directory).filter((name) =>
  name.endsWith(".schema.json"),
)) {
  ajv.addSchema(JSON.parse(readFileSync(new URL(name, directory))));
}
let source = standaloneCode(
  ajv,
  Object.fromEntries(
    Object.entries(names).map(([name, file]) => [
      name,
      `https://haddenindustries.com/ontology/contracts/v1/${file}.v1.schema.json`,
    ]),
  ),
);
// Ajv's standalone ESM still emits CommonJS runtime references. Adapt only its documented runtime imports.
const imports = new Map();
source = source.replace(
  /require\("(ajv\/dist\/runtime\/[a-zA-Z0-9]+)"\)\.default/gu,
  (_match, specifier) => {
    if (!imports.has(specifier)) {
      imports.set(specifier, `runtime${imports.size}`);
    }
    return imports.get(specifier);
  },
);
if (/\brequire\(/u.test(source)) {
  throw new Error("Unexpected native validator runtime dependency.");
}
source =
  [...imports]
    .map(
      ([specifier, name]) =>
        `import ${name}Module from "${specifier}.js";\nconst ${name} = ${name}Module.default ?? ${name}Module;`,
    )
    .join("\n") +
  "\n" +
  source;
async function emit(name, source) {
  const target = fileURLToPath(
    new URL(`../src/ontology-loading/${name}`, import.meta.url),
  );
  const generated = await format(
    "// Generated by util/generateOntologyCacheValidators.mjs from the pinned provider schemas.\n" +
      source,
    { parser: "babel" },
  );
  if (process.argv.includes("--check")) {
    if (readFileSync(target, "utf8") !== generated) {
      throw new Error(`Generated ${name} differs from the pinned schemas.`);
    }
  } else {
    writeFileSync(target, generated);
  }
}

// Project only presentation metadata into startup code; schema validators stay lazy.
const common = JSON.parse(
  readFileSync(new URL("ontology-contract-common.v1.schema.json", directory)),
);
const definition = common.$defs.documentValidationProfile;
const choices = definition.oneOf.map((descriptor) => ({
  id: descriptor.$anchor,
  title: descriptor.title,
  description: descriptor.description,
  validationProfileId: descriptor.properties.validationProfileId.const,
  parseMode: descriptor.properties.parseMode.const,
}));
const defaultChoice = choices.find(
  ({ validationProfileId, parseMode }) =>
    validationProfileId === definition.default.validationProfileId &&
    parseMode === definition.default.parseMode,
);
if (!defaultChoice) {
  throw new Error("Provider parsing metadata has no matching default.");
}
await emit(
  "owlMappingDefinitions.js",
  `export const owlMappingDefinitions = ${JSON.stringify({ defaultStrategy: defaultChoice.id, choices })};\n`,
);
await emit("ontologyCacheValidators.js", source);
